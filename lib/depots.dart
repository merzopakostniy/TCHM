/// Справочник депо Московского метрополитена.
///
/// Пока список зашит в приложение: до появления серверной части брать его
/// неоткуда. Как только заработает бэкенд из плана расширения, справочник
/// переезжает в таблицу `depots`, а этот файл остаётся только запасным
/// вариантом для демо-режима.
///
/// Строящиеся Троицкое и Бирюлёво не включены: машинистов в них ещё нет.
/// Добавить — одна строка, когда откроются.
library;

class Depot {
  const Depot({
    required this.id,
    required this.name,
    this.number,
    this.line = '',
  });

  /// Идентификатор в базе: `tch16`. Именно он попадёт в профиль пользователя
  /// и в данные штата, поэтому меняться не должен никогда.
  /// Штаты разных линий одного депо имеют разные id.
  final String id;

  /// Номер депо: ТЧ-16. Пусто у депо, которому номер ещё не присвоен, —
  /// такое бывает у новостроек: депо уже есть, приказа с номером ещё нет.
  final int? number;

  /// Название: «Митино».
  final String name;

  /// Линия, которую обслуживает депо: нужна только чтобы человек не
  /// перепутал депо в длинном списке. Пусто там, где линия не уточнена.
  final String line;

  /// В интерфейсе депо показывается одним названием: «Митино». Номер ТЧ
  /// остаётся в данных — он входит в идентификатор и задаёт порядок в этом
  /// файле, — но на экране его нет: у новых депо номера может не быть вовсе,
  /// а пустое место в колонке номеров ломало бы строй списка.
  String get title => name;

  /// Строка для поиска по списку. Номер ТЧ в неё входит, хотя на экране его
  /// нет: «16» — привычный способ назвать своё депо, и поиск обязан его
  /// понимать.
  String get searchText => '${number ?? ''} $name $line'.toLowerCase();

  /// Ключ сортировки по алфавиту. «ё» приравнена к «е»: иначе Руднёво
  /// уезжает в конец списка, за «я».
  String get sortKey => name.toLowerCase().replaceAll('ё', 'е');
}

